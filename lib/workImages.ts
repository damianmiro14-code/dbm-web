function hashString(input: string): number {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function pickWorkImages(seed: string, count: number, startOffset = 0): string[] {
  const total = WORK_IMAGES.length;

  if (total <= 0) return [];
  if (total === 1) return [WORK_IMAGES[0]];

  const h = hashString(seed);
  const step = (h % (total - 1)) + 1; // 1..total-1
  let idx = (h + startOffset) % total;

  const out: string[] = [];
  const safeCount = Math.max(1, Math.min(count, total));

  for (let i = 0; i < safeCount; i++) {
    out.push(WORK_IMAGES[idx]);
    idx = (idx + step) % total;
  }
  return out;
}
